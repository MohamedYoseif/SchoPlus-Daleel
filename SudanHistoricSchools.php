    /**
     * Match and generate a complete historical dossier for a given school
     */
    public static function getDossier(array $school): ?array
    {
        if (!self::isHistoric($school)) {
            return null;
        }

        $dossiers = self::initDossiers();
        $name = $school['name'] ?? '';
        $nameEn = $school['name_en'] ?? '';
        $slug = $school['slug'] ?? '';
        $year = (int)($school['established_year'] ?? 0);
        $legacyYears = ($year > 1800) ? ((int)date('Y') - $year) : null;

        // Try exact keyword match first
        foreach ($dossiers as $key => $d) {
            if (mb_stripos($name, $key) !== false || mb_stripos($slug, $key) !== false || mb_stripos($nameEn, $key) !== false) {
                $res = $d;
                $res['established_year'] = $d['established_year'] ?: $year;
                $res['legacy_years'] = ((int)date('Y') - $res['established_year']);
                return $res;
            }
