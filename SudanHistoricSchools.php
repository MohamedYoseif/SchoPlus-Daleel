    /**
     * Check if a school qualifies as a historic heritage school
     */
    public static function isHistoric(array $school): bool
    {
        if (!empty($school['is_historic'])) {
            return true;
        }

        $year = (int)($school['established_year'] ?? 0);
        if ($year > 1800 && $year <= 1960) {
            // Note: Verify not a modern private school mislabeled
            if (($school['school_type'] ?? '') === 'private' && mb_stripos($school['name'] ?? '', 'كمبوني') === false && mb_stripos($school['name'] ?? '', 'راهبات') === false) {
                return false;
            }
            return true;
        }

        if ((int)($school['historic_votes'] ?? 0) >= 500) {
            return true;
        }

        $name = $school['name'] ?? '';
        $nameEn = $school['name_en'] ?? '';
        $iconicKeys = [
            'وادي سيدنا', 'خور طقت', 'حنتوب', 'بخت الرضا', 'رفاعة', 'بابكر بدري',
            'الأهلية أم درمان', 'أم درمان الأهلية', 'المؤتمر الثانوية', 'بربر الثانوية',
            'الخرطوم القديمة', 'بحري الثانوية القديمة', 'كمبوني', 'الراهبات', 'Sister',
            'الأميرية بورتسودان', 'بورتسودان القديمة', 'كسلا الثانوية', 'دنقلا الثانوية',
            'شندي الثانوية', 'عطبرة الثانوية القديمة', 'الفاشر الثانوية القديمة',
            'كوستي الأهلية', 'الدلنج الثانوية', 'الشيخ مصطفى الأمين', 'أم درمان النموذجية بنات',
            'بيت المال'
        ];

        foreach ($iconicKeys as $k) {
            if (mb_stripos($name, $k) !== false || mb_stripos($nameEn, $k) !== false) {
                return true;
            }
        }

        return false;
    }

